import { test, expect, type Page } from "@playwright/test";
async function login(page: Page) {
  await page.goto("/");
  await page.getByRole("button", { name: "Skip intro", exact: true }).click();
  await page.getByRole("button", { name: "Find your people", exact: true }).click();
  await page.locator("label.choice-chip").filter({ has: page.getByRole("radio", { name: "Log in", exact: true }) }).click();
  await page.getByRole("button", { name: "Continue with Google", exact: true }).click();
  await page.getByRole("button", { name: "Continue as Alex", exact: true }).click();
  await page.getByRole("button", { name: "Create meal", exact: true }).click();
}
test("map previews a sample without committing it; search and viewport controls work", async ({ page }) => {
  await login(page);
  const map = page.getByRole("region", { name: "Restaurant map", exact: true });
  await map.getByRole("button", { name: "Show Casa Evening", exact: true }).click();
  await expect(page.locator(".venue-selection-status")).toContainText("The Little Table");
  await expect(page.getByLabel("Restaurant preview")).toContainText("Casa Evening");
  await page.getByRole("button", { name: "Cancel selection", exact: true }).click();
  await expect(page.locator(".venue-selection-status")).toContainText("The Little Table");
  await page.getByRole("textbox", { name: "Search restaurants or areas", exact: true }).fill("Seasonal");
  await page.keyboard.press("Tab");
  await page.getByRole("button", { name: "The Garden Kitchen St James’s · Seasonal", exact: true }).click();
  await page.getByRole("button", { name: "Use this restaurant", exact: true }).click();
  await expect(page.locator(".venue-selection-status")).toContainText("The Garden Kitchen");
  await map.scrollIntoViewIfNeeded();
  const before = await map.locator(".demo-map-world").getAttribute("style");
  const box = (await map.boundingBox())!;
  await page.mouse.move(box.x + box.width * .3, box.y + box.height * .8);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .9, { steps: 8 });
  await page.mouse.up();
  await expect(map.locator(".demo-map-world")).not.toHaveAttribute("style", before!);
  await expect(page.getByLabel("Restaurant preview")).toHaveCount(0);
  await map.getByRole("button", { name: "Zoom in", exact: true }).click();
  await expect(map).toHaveAttribute("data-zoom", "1.3");
  await map.getByRole("button", { name: "Search this area", exact: true }).click();
  await map.getByRole("button", { name: "Show central London", exact: true }).click();
  await expect(map).toHaveAttribute("data-zoom", "1.0");
  await page.screenshot({ path: "qa/restaurant-picker-2026-10-21/map-selection.png" });
});
test("arbitrary restaurant requires full details and explicit confirmation, then publishes and edits safely", async ({ page }) => {
  await page.setViewportSize({ width: 430, height: 932 });
  await login(page);
  await page.getByRole("textbox", { name: "Search restaurants or areas", exact: true }).fill("Dockside Kitchen");
  await page.keyboard.press("Tab");
  await expect(page.getByText("No sample restaurants match. Add your restaurant below.", { exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Search Google Maps", exact: false })).toHaveAttribute("href", /query=Dockside\+Kitchen/);
  await page.getByRole("button", { name: "Add a restaurant", exact: true }).click();
  await page.getByRole("button", { name: "Preview restaurant", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("full restaurant address");
  await page.getByRole("textbox", { name: "Full address", exact: true }).fill("25 Test Road, London E14 0XX");
  await page.getByRole("textbox", { name: "Neighbourhood or area", exact: true }).fill("Canary Wharf");
  await page.getByRole("button", { name: "Preview restaurant", exact: true }).click();
  await expect(page.locator(".venue-selection-status")).toContainText("The Little Table");
  await page.getByRole("button", { name: "Use this restaurant", exact: true }).click();
  await expect(page.locator(".venue-selection-status")).toContainText("Dockside Kitchen");
  await expect(page.locator(".venue-selection-status")).toContainText("25 Test Road");
  await page.getByLabel("Time", { exact: true }).selectOption("19:00");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Give your meal a name", { exact: true }).fill("A supper by the docks");
  await page.getByLabel("What should people expect?", { exact: true }).fill("A relaxed evening with new neighbours and friendly conversation.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("radio", { name: "Book through the app", exact: true })).toHaveCount(0);
  await page.getByRole("checkbox", { name: /I have a reservation/ }).check();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("checkbox", { name: /I’ve checked the arrangements/ }).check();
  await page.getByRole("button", { name: "Publish meal", exact: true }).click();
  await expect(page.getByRole("heading", { name: "A supper by the docks", exact: true })).toBeVisible();
  await expect(page.getByText("25 Test Road, London E14 0XX", { exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Open Dockside Kitchen in Google Maps", exact: false })).toHaveAttribute("href", /Dockside\+Kitchen.*25\+Test\+Road/);
  await page.screenshot({ path: "qa/restaurant-picker-2026-10-21/arbitrary-restaurant-published.png" });
  await page.getByRole("button", { name: "Manage applications", exact: true }).click();
  await page.getByRole("button", { name: "Edit arrangements", exact: true }).click();
  await expect(page.locator(".venue-selection-status")).toContainText("Dockside Kitchen");
  await expect(page.getByLabel("Time", { exact: true })).toHaveValue("19:00");
});
test("time dropdown, linked terms and post-publish back follow the meal journey", async ({ page }) => {
  await login(page);
  await expect(page.getByLabel("Time", { exact: true }).locator("option")).toHaveCount(49);
  await page.getByLabel("Time", { exact: true }).selectOption("22:00");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Give your meal a name", { exact: true }).fill("A late table with friends");
  await page.getByLabel("What should people expect?", { exact: true }).fill("Meet for a relaxed dinner with neighbours and easy conversation.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("checkbox", { name: /I have a reservation/ }).check();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("link", { name: "cancellation terms", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Cancellation terms", exact: true })).toBeVisible();
  await expect(page.getByText(/There is no in-app payment to refund/)).toBeVisible();
  await page.getByRole("button", { name: "Back to review", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: /I’ve checked the arrangements/ })).not.toBeChecked();
  await page.getByRole("checkbox", { name: /I’ve checked the arrangements/ }).check();
  await page.getByRole("button", { name: "Publish meal", exact: true }).click();
  await expect(page.locator(".host-line > div button svg")).toHaveCount(0);
  await page.getByRole("button", { name: "Go back", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your next good meal.", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Open A late table with friends", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Publish meal", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Profile", exact: true }).click();
  await page.getByRole("button", { name: "Go back", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your next good meal.", exact: true })).toBeVisible();
  await page.screenshot({ path: "qa/restaurant-picker-2026-10-21/publish-back-to-meals.png" });
});
